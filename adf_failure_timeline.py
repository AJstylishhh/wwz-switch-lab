#!/usr/bin/env python3
"""Summarize where known failure words occur within private WWZ ADF packs.

Designed for the test operator's LOCAL --capture-dir folder. Only preselected
keywords, relative offsets, and counts are printed. Never dump decoded ADF,
user IDs, session IDs, tokens, source filenames, arbitrary strings or hex.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path

from diagnostic_deep_probe import (
    DIAG_ROUTE, MAX_CAPTURE, bounded_decompress, compression_kind,
)
from wwz_wire import fields

# Only fixed public words, not regex captures or arbitrary surrounding text.
WORDS = {
    "error": b"error",
    "failed": b"failed",
    "timeout": b"timeout",
    "disconnect": b"disconnect",
    "not_connected": b"not connected",
    "offline": b"offline",
    "invalid": b"invalid",
    "subscription": b"subscription",
}
PAIRS = (
    ("error", "not_connected"), ("error", "timeout"),
    ("failed", "timeout"), ("failed", "not_connected"),
    ("disconnect", "error"), ("disconnect", "not_connected"),
)
MAX_PACKS = 256
NEARBY = 96


def positions(data: bytes):
    low = data.lower()
    found = {}
    for label, needle in WORDS.items():
        start = 0
        hits = []
        while len(hits) < 5000:
            pos = low.find(needle, start)
            if pos < 0:
                break
            hits.append(pos)
            start = pos + len(needle)
        if hits:
            found[label] = hits
    return found


def close_hits(left, right):
    """Linear two-pointer proximity check for bounded, sorted offsets."""
    i = j = 0
    while i < len(left) and j < len(right):
        if abs(left[i] - right[j]) <= NEARBY:
            return True
        if left[i] < right[j]:
            i += 1
        else:
            j += 1
    return False


def safe_part_summary(data: bytes):
    hits = positions(data)
    near = []
    for a, b in PAIRS:
        if a in hits and b in hits and close_hits(hits[a], hits[b]):
            near.append(a + "+" + b)
    first = min((p for entries in hits.values() for p in entries), default=None)
    region = None if first is None else (
        "first_third" if 3 * first < len(data) else
        "middle_third" if 3 * first < 2 * len(data) else "last_third")
    return {
        "size": len(data),
        "keyword_counts": {k: len(v) for k, v in sorted(hits.items())},
        "keyword_pairs_within_96_bytes": near,
        "first_keyword_region": region,
    }


def inspect_capture(raw: bytes):
    result = {}
    for field, wire, payload in fields(raw):
        if wire != 2 or field not in (1, 2):
            continue
        key = "data" if field == 1 else "entries"
        kind = compression_kind(payload)
        if kind == "zlib_possible":
            decompressed = bounded_decompress(payload, 15)
        elif kind == "gzip":
            decompressed = bounded_decompress(payload, 31)
        else:
            decompressed = None
        if decompressed is None:
            result[key] = {"compressed": kind, "decoded": False}
        else:
            result[key] = safe_part_summary(decompressed)
    return result


def analyze(folder: Path):
    if not folder.is_dir():
        raise ValueError("capture directory does not exist")
    reports = []
    skipped = 0
    metadata_files = sorted(folder.glob("*.json"))
    for path in metadata_files:
        if len(reports) >= MAX_PACKS:
            break
        try:
            meta = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(meta, dict) or str(meta.get("path", "")).lower() != DIAG_ROUTE:
                continue
            binary = path.with_suffix(".bin")
            if not binary.is_file() or binary.stat().st_size > MAX_CAPTURE:
                skipped += 1
                continue
            report = inspect_capture(binary.read_bytes())
            reports.append({"order": len(reports) + 1, **report})
        except (ValueError, OSError, UnicodeError):
            skipped += 1
    totals = Counter()
    nearby = Counter()
    per_section = Counter()
    for pack in reports:
        for section in ("data", "entries"):
            part = pack.get(section, {})
            for label, count in part.get("keyword_counts", {}).items():
                totals[label] += count
                per_section[section + ":" + label] += 1
            for pair in part.get("keyword_pairs_within_96_bytes", []):
                nearby[pair] += 1
    return {
        "packs_examined": len(reports),
        "skipped": skipped,
        "occurrence_totals": dict(sorted(totals.items())),
        "packs_with_keyword_by_section": dict(sorted(per_section.items())),
        "close_keyword_pairs_by_part": dict(sorted(nearby.items())),
        "chronological_parts": reports,
        "warning": (
            "Sorted by capture filename (timestamps if generated by mvp_server). "
            "Keyword proximity is not proof of a causal error. No raw ADF "
            "strings, filenames or player/account values are emitted."
        ),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("captures", nargs="?", type=Path, default=Path("captures"))
    args = parser.parse_args()
    print(json.dumps(analyze(args.captures), indent=2))


if __name__ == "__main__":
    main()
